const labels = {
  quote: "오늘의 명언",
  english: "오늘의 영어",
  bible: "말씀의 의미",
  quiz: "1분 퀴즈"
};

const categoryOffsets = {
  quote: 0,
  english: 7,
  bible: 13,
  quiz: 19
};

function getKoreaDateKey() {
  const formatter = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit"
  });
  return formatter.format(new Date());
}

function getKoreaDayNumber() {
  const [year, month, day] = getKoreaDateKey().split("-").map(Number);
  return Math.floor(Date.UTC(year, month - 1, day) / 86400000);
}

function getDailyIndex(category) {
  const list = content[category];
  return (getKoreaDayNumber() + categoryOffsets[category]) % list.length;
}

function getTodayViewedCount() {
  const dateKey = getKoreaDateKey();
  const savedDate = localStorage.getItem("threeMinuteViewedDate");
  if (savedDate !== dateKey) {
    localStorage.setItem("threeMinuteViewedDate", dateKey);
    localStorage.setItem("threeMinuteViewed", "0");
    return 0;
  }
  return Number(localStorage.getItem("threeMinuteViewed") || 0);
}

const state = {
  category: "quote",
  index: 0,
  pinnedCard: false,
  viewed: getTodayViewedCount()
};

const categoryButtons = [...document.querySelectorAll(".category")];
const badge = document.querySelector("#badge");
