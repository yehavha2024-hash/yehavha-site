let deferredInstallPrompt = null;
let toastTimer = null;

function randomIndex(length, current = -1) {
  if (length <= 1) return 0;
  let next = current;
  while (next === current) next = Math.floor(Math.random() * length);
  return next;
}

function setUrl() {
  const url = new URL(window.location.href);

  if (state.category === "quote") url.searchParams.delete("category");
  else url.searchParams.set("category", state.category);

  if (state.pinnedCard) url.searchParams.set("card", String(state.index));
  else url.searchParams.delete("card");

  history.replaceState(null, "", url);
}

function renderQuiz(item) {
  quizArea.innerHTML = "";
  quizArea.hidden = false;

  const options = document.createElement("div");
  options.className = "quiz-options";

  item.options.forEach((option, optionIndex) => {
    const button = document.createElement("button");
    button.className = "quiz-option";
    button.textContent = option;
    button.addEventListener("click", () => {
      const all = [...options.querySelectorAll("button")];
      all.forEach((btn) => { btn.disabled = true; });
      button.classList.add(optionIndex === item.answer ? "correct" : "wrong");
      if (optionIndex !== item.answer) all[item.answer].classList.add("correct");
      result.textContent = optionIndex === item.answer
        ? `정답입니다. ${item.explanation}`
        : `아쉽습니다. ${item.explanation}`;
    });
    options.appendChild(button);
  });

  const result = document.createElement("p");
  result.className = "quiz-result";
  quizArea.append(options, result);
}

function render({ countView = false } = {}) {
  const list = content[state.category];
  state.index = Math.max(0, Math.min(state.index, list.length - 1));
  const item = list[state.index];

  categoryButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.category === state.category);
  });

  document.body.dataset.category = state.category;

  badge.textContent = labels[state.category];
  counter.textContent = state.pinnedCard
    ? `${state.index + 1} / ${list.length}`
    : `오늘의 카드 · ${state.index + 1} / ${list.length}`;
  cardTitle.textContent = item.title;
  cardBody.textContent = item.body;
  cardMeta.textContent = item.meta;

  if (state.category === "quiz") renderQuiz(item);
  else {
    quizArea.hidden = true;
    quizArea.innerHTML = "";
  }

  if (countView) {
    state.viewed += 1;
    localStorage.setItem("threeMinuteViewedDate", getKoreaDateKey());
    localStorage.setItem("threeMinuteViewed", String(state.viewed));
  }
  viewCount.textContent = `${state.viewed}개`;
  setUrl();
}

function showToast(message) {
  clearTimeout(toastTimer);
  toast.textContent = message;
  toast.classList.add("show");
  toastTimer = setTimeout(() => toast.classList.remove("show"), 2200);
}

categoryButtons.forEach((button) => {
  button.addEventListener("click", () => {
    state.category = button.dataset.category;
    state.index = getDailyIndex(state.category);
    state.pinnedCard = false;
    render({ countView: true });
  });
});

nextBtn.addEventListener("click", () => {
  state.index = randomIndex(content[state.category].length, state.index);
  state.pinnedCard = true;
  render({ countView: true });
});

shareBtn.addEventListener("click", async () => {
  const item = content[state.category][state.index];
  const shareData = {
    title: `3분 쉼표 · ${labels[state.category]}`,
    text: `${item.title}\n${item.body}`,
    url: window.location.href
  };

  try {
    if (navigator.share) {
      await navigator.share(shareData);
    } else {
      await navigator.clipboard.writeText(`${shareData.text}\n${shareData.url}`);
      showToast("공유 문구와 링크를 복사했습니다.");
    }
  } catch (error) {
    if (error.name !== "AbortError") {
      try {
        await navigator.clipboard.writeText(`${shareData.text}\n${shareData.url}`);
        showToast("링크를 복사했습니다. 카카오톡에 붙여넣으세요.");
      } catch {
        showToast("브라우저 메뉴에서 링크를 공유해 주세요.");
      }
    }
  }
});

window.addEventListener("beforeinstallprompt", (event) => {
  event.preventDefault();
  deferredInstallPrompt = event;
  installBtn.hidden = false;
});

installBtn.addEventListener("click", async () => {
  if (!deferredInstallPrompt) return;
  deferredInstallPrompt.prompt();
  await deferredInstallPrompt.userChoice;
  deferredInstallPrompt = null;
  installBtn.hidden = true;
});

function loadFromUrl() {
  const params = new URLSearchParams(window.location.search);
  const category = params.get("category");
  const cardParam = params.get("card");
  const card = Number(cardParam);

  if (category && content[category]) state.category = category;

  if (
    cardParam !== null
    && Number.isInteger(card)
    && card >= 0
    && card < content[state.category].length
  ) {
    state.index = card;
    state.pinnedCard = true;
  } else {
    state.index = getDailyIndex(state.category);
    state.pinnedCard = false;
  }
}

if ("serviceWorker" in navigator) {
  window.addEventListener("load", () => navigator.serviceWorker.register("./sw.js").catch(() => {}));
}

loadFromUrl();
render({ countView: true });
