  const unique = values => [...new Set((values || []).filter(Boolean))];
  const sentences = text => String(text || '').split(/(?<=[.!?다])\s+/).map(v => v.trim()).filter(Boolean);

  function areaProfile(record) {
    for (const area of record.legalAreas || []) if (AREA[area]) return AREA[area];
    return AREA['법철학·규제이론'];
  }

  function issuePoints(record) {
    return unique((record.issues || []).flatMap(issue => ISSUE[issue] || [])).slice(0, 4);
  }

  function makeLead(record, profile) {
    const focus = record.focus || record.summary || (record.issues || []).join('·') || record.title;
    const existing = sentences(record.summary);
    const first = `이 문헌의 핵심은 ${focus}을(를) 단순한 기술문제가 아니라 “${profile.question}”라는 법적 문제로 전환하는 데 있다.`;
    const second = existing[0] && !existing[0].includes('적용·한계와 제도적 대응을 검토하는 문헌') ? existing[0] : profile.proposition;
    const third = `따라서 이 문헌은 ${record.evidenceRoles?.includes('반대학설') ? '현재 연구의 주장을 제한하는 경쟁견해를 검증하는 자료' : record.evidenceRoles?.includes('비교법') ? '국내법의 제도설계와 외국법의 기능을 비교하는 자료' : '책임요건·권리·절차 또는 법적 지위의 구체적 논증근거'}로 읽는 것이 적절하다.`;
    return [first, second, third];
  }

  function makeQuestions(record, profile) {
    const result = [profile.question];
    (record.issues || []).slice(0, 3).forEach(issue => result.push(`${issue}을(를) 현행 법리의 어떤 요건에 연결하고, 그 요건이 AI의 기술적 특성 때문에 어떻게 수정되는가?`));
    return unique(result).slice(0, 4);
  }

  function makeArgumentMap(record, profile) {
    const focus = record.focus || (record.issues || []).join('·') || record.title;
    return [
      `문제설정 — ${focus}에서 기존 법리가 전제한 인간의 직접행위·정보대칭·통제가능성이 그대로 유지되는지 확인한다.`,
      `법적 분해 — ${profile.question}라는 중심질문을 책임주체, 의무의 내용, 인과·증명, 권리구제 또는 제도설계의 하위문제로 나눈다.`,
      '규범판단 — 기술적 자율성 자체가 아니라 위험창출, 통제권, 정보접근성, 보호법익과 기존 법체계의 목적을 기준으로 해결방안을 평가한다.',
      '연구접목 — 문헌의 결론을 그대로 채택하기보다 현재 연구의 계층적 책임귀속·기능적 단위·로그·책임재산 설계 중 어느 요소를 지지하거나 제한하는지 명시한다.'
    ];
  }

  function makePropositions(record, profile) {
    const focus = record.focus || (record.issues || []).join('·') || record.title;
    const result = [profile.proposition, `${focus}에 관한 논증에서는 기술적 원인과 법적 귀속근거를 구별하고, 책임을 부과하는 규범적 이유를 별도로 제시해야 한다.`];
    if ((record.evidenceRoles || []).includes('반대학설')) result.push('새로운 AI 전용 책임주체나 독립 제도를 도입하기 전에 기존 과실·감독·조직책임 법리의 조정 가능성을 먼저 검증해야 한다.');
    else if ((record.evidenceRoles || []).includes('비교법')) result.push('외국 제도의 조문을 직접 이식하기보다 그 제도가 해결하는 위험과 집행기능을 국내법의 대응제도와 비교해야 한다.');
    else result.push('AI의 복잡성과 불투명성은 책임 공백의 이유가 아니라 의무구체화·기록보존·증명위험 배분을 정교화해야 할 이유로 사용할 수 있다.');
    return unique(result).slice(0, 4);
  }

  function makeCitationTargets(record) {
    const focus = record.focus || (record.issues || []).join('·') || record.title;
    return [
      `서론·문제제기에서 ${focus}을(를) 기존 법리로 해결하기 어려운 이유를 어떻게 정식화하는지 확인`,
      '본문에서 핵심 법률개념의 정의와 성립요건을 어떤 법조문·판례·선행연구에 근거시키는지 확인',
      '저자가 제시하는 책임주체·의무·절차·제도대안의 구체적 요건과 예외를 확인',
      '결론에서 적용범위와 한계를 어떻게 제한하는지 확인하고 직접 인용할 경우 정확한 문장·쪽수를 기록'
    ];
  }

  for (const record of records) {
    const profile = areaProfile(record);
    record.researchNote = {
      lead: record.researchNote?.lead || makeLead(record, profile),
      legalQuestions: record.researchNote?.legalQuestions || makeQuestions(record, profile),
      doctrinalPoints: record.researchNote?.doctrinalPoints || unique([...profile.doctrines, ...issuePoints(record)]).slice(0, 7),
      argumentMap: record.researchNote?.argumentMap || makeArgumentMap(record, profile),
      propositions: record.researchNote?.propositions || makePropositions(record, profile),
      citationTargets: record.researchNote?.citationTargets || makeCitationTargets(record),
      sourceBasis: record.researchNote?.sourceBasis || '서지·초록·기존 개별 요약과 법영역별 교리를 결합한 논증용 연구노트. 직접 인용 전에는 반드시 원문과 쪽수를 재확인.'
    };
  }
