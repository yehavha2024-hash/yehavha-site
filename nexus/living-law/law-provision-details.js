  const PHRASE_DETAILS = [
    {
      test: (text) => text.includes('응급조치') && text.includes('긴급응급조치') && !text.includes('잠정조치'),
      refs: [`${FULL_STALKING} 제3조`, `${FULL_STALKING} 제4조`]
    },
    {
      test: (text) => text.includes('긴급응급조치') && text.includes('잠정조치'),
      refs: [`${FULL_STALKING} 제4조`, `${FULL_STALKING} 제9조`]
    }
  ];

  function normalizeText(text) {
    let out = String(text || '').replace(/\s+/g, ' ').trim();
    ALIASES.forEach(([shortName, fullName]) => { out = out.replaceAll(shortName, fullName); });
    return out;
  }

  function actFrom(ref) {
    const match = ref.match(/^(.+?)\s+제\d/);
    return match ? match[1].trim() : '';
  }

  function provisionKeys(ref, inheritedAct) {
    let normalized = normalizeText(ref);
    if (/^제\d/.test(normalized) && inheritedAct) normalized = `${inheritedAct} ${normalized}`;
    const phrase = PHRASE_DETAILS.find((entry) => entry.test(normalized));
    if (phrase) return { normalized, act: FULL_STALKING, keys: phrase.refs };

    const act = actFrom(normalized) || inheritedAct || '';
    const articleMatches = [...normalized.matchAll(/제(\d+)조(?:의(\d+))?/g)];
    if (!articleMatches.length) return { normalized, act, keys: [] };
    return {
      normalized,
      act,
      keys: articleMatches.map((m) => `${act} 제${m[1]}조${m[2] ? `의${m[2]}` : ''}`)
    };
  }

  function ensureTitle(card, title) {
    if (!title) return;
    let el = card.querySelector('.law-guide-title');
    if (!el) {
      el = document.createElement('span');
      el.className = 'law-guide-title';
      card.querySelector('.law-guide-heading')?.append(el);
    }
    el.textContent = title;
  }

  function enrich() {
    const cards = [...document.querySelectorAll('#dialogBody .law-guide-card')];
    let inheritedAct = '';
    cards.forEach((card) => {
      const refEl = card.querySelector('.law-guide-ref');
      const plainEl = card.querySelector('.law-guide-plain');
      if (!refEl || !plainEl) return;

      const raw = refEl.textContent;
      const parsed = provisionKeys(raw, inheritedAct);
      if (parsed.act) inheritedAct = parsed.act;
      const details = parsed.keys.map((key) => ({ key, value: P[key] })).filter((entry) => entry.value);
      if (!details.length) return;

      if (details.length === parsed.keys.length) {
        refEl.textContent = details.map((entry) => entry.key).join(' · ');
      } else if (/^제\d/.test(normalizeText(raw)) && details.length === 1) {
        refEl.textContent = details[0].key;
      } else {
        refEl.textContent = normalizeText(raw);
      }

      ensureTitle(card, details.map((entry) => entry.value[0]).join(' · '));
      plainEl.textContent = details.length === 1
        ? `조문 규정 내용: ${details[0].value[1]}`
        : `조문 규정 내용: ${details.map((entry, index) => `${index + 1}) ${entry.key} — ${entry.value[1]}`).join(' ')}`;
    });
  }

  const target = document.getElementById('dialogBody');
  if (!target) return;
  new MutationObserver(() => requestAnimationFrame(enrich)).observe(target, { childList: true, subtree: true });
  document.addEventListener('click', (event) => {
    if (event.target.closest?.('.detail-button')) requestAnimationFrame(enrich);
  });
